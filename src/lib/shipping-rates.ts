export const NIGERIAN_STATES = Object.keys(SHIPPING_RATES).sort();

export const getCityRate = (state: string, city: string): CityRate | undefined =>
  SHIPPING_RATES[state]?.find((c) => c.city === city);

export const getShippingFee = (
  state: string,
  city: string,
  method: ShippingMethod,
): number => {
  const rate = getCityRate(state, city);
  if (!rate) return 0;
  return method === "doorstep" ? rate.door : rate.park;
};
